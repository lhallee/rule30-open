# Reports


def ratios(counts: np.ndarray, n: int, first: int, number: int) -> np.ndarray:
    """counts[n + j + 1] / counts[n + j] for j = first .. first + number - 1, while the counts are positive."""
    # counts: (cap + 1,)
    q = [counts[n + j + 1] / counts[n + j] for j in range(first, first + number)
         if n + j + 1 < len(counts) and counts[n + j] > 0]
    return np.array(q)  # (<= number,)


def report_bwh(lo: int, hi: int) -> None:
    print("n  M(n,2) M(n,3) horizon  witnesses(c=2,3)  max|ratio-1/2| over the first 11 forced symbols (c=2,3)  "
          "survivors at n+j for j = n-6 .. n+2 (c=2 | c=3)")
    for n in tqdm(range(lo, hi + 1), desc="BWH", file=sys.stderr):
        r = c_runs(n, cap=2 * n + 8)
        M = [int(np.flatnonzero(r.counts[i])[-1]) - n for i in range(2)]
        tail = [r.counts[i, max(n, 2 * n - 6):2 * n + 3].tolist() for i in range(2)]
        dev = [f"{np.abs(ratios(r.counts[i], n, 0, 11) - 0.5).max():.3f}" for i in range(2)]
        print(n, M[0], M[1], n + 2, int(r.counts[0, 2 * n + 2]), int(r.counts[1, 2 * n + 2]), *dev, tail[0], "|",
              tail[1], flush=True)


def report_rw(lo: int, hi: int) -> None:
    print("n  longest run past the free prefix (c=2, c=3)  0.766 n  witnesses (c=2: r=0,1,2; c=3: r=0,1,2)  "
          "survival ratio of the first forced symbol, and the range of the next nine (c=2; c=3)")
    for n in tqdm(range(lo, hi + 1), desc="RW", file=sys.stderr):
        r = c_runs(n, hard_core=True, cap=2 * n + 12)
        J = [int(np.flatnonzero(r.counts[i])[-1]) - n for i in range(2)]
        rng = []
        for i in range(2):
            q = ratios(r.counts[i], n, 0, 10)  # (<= 10,)
            rng.append(f"{q[0]:.3f} {q[1:].min():.3f}-{q[1:].max():.3f}" if len(q) == 10 else "-")
        print(n, J[0], J[1], f"{0.766 * n:.1f}", r.rw[0].tolist(), r.rw[1].tolist(), "; ".join(rng), flush=True)


def report_clumps(lo: int, hi: int, hard_core: bool, back: int = 3) -> None:
    """At the last `back` lengths that a run reaches (with at most 5000 survivors): survivors, clumps (classes of the
    survivors that agree from position n // 2 on), the least f for which they form one clump, the least, the median and
    the largest head depth, and at the last length the edges E_L on which the survivors die."""
    print("n c L survivors clumps(f=n//2) one_clump_from head_depth(min, median, max) [death edges]")
    for n in tqdm(range(lo, hi + 1), desc="clumps", file=sys.stderr):
        first = c_runs(n, hard_core=hard_core, cap=2 * n + 12)
        lasts = [int(np.flatnonzero(first.counts[i])[-1]) for i in range(2)]
        starts = [next(L for L in range(lasts[i] - back + 1, lasts[i] + 1) if first.counts[i, L] <= 5000)
                  for i in range(2)]
        r = c_runs(n, hard_core=hard_core, cap=2 * n + 12, dump_from=min(starts))
        for c in (2, 3):
            for L in range(starts[c - 2], lasts[c - 2] + 1):
                runs = [(p, reach) for cc, p, reach in r.dumped if cc == c and reach >= L]
                S = survivors_at(n, c, hard_core, runs, L)
                depths = sorted(head_depth(S, w, n) for w in S)
                one = next(f for f in range(L + 1) if len(clumps(S, f)) == 1)
                edges = ""
                if L == lasts[c - 2]:
                    found = set()
                    for w in S:
                        cone = Cone(n)
                        for x in w:
                            cone.push(x)
                        found.add(tuple(sorted(cone.edge())))
                    edges = str(sorted(found))
                print(n, c, L, len(S), len(clumps(S, n // 2)), one, depths[0], depths[len(depths) // 2], depths[-1],
                      edges, flush=True)


def report_edges(n: int) -> None:
    for c in (2, 3):
        t = edge_census(n, c, progress=True)["table"]  # (E, E', a, survived)
        print(f"n={n} c={c}: steps {t.sum()}, survived {t[..., 1].sum()}")
        print("  edge E_k of the wedge values: steps per edge", [int(t[i].sum()) for i in range(4)],
              "survived", [int(t[i, ..., 1].sum()) for i in range(4)], "edges", [sorted(x) for x in EDGES])
        inner = t[:, 2]  # (E, a, survived): E'_k = {1, 2}
        print("  E'_k = {1,2}: fraction of steps", f"{inner.sum() / t.sum():.3f}",
              "; survival by a = 0..3:", [f"{inner[:, a, 1].sum() / max(1, inner[:, a].sum()):.3f}" for a in range(4)])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bwh", nargs=2, type=int)
    ap.add_argument("--rw", nargs=2, type=int)
    ap.add_argument("--clumps", nargs=2, type=int)
    ap.add_argument("--rw-clumps", nargs=2, type=int)
    ap.add_argument("--edges", type=int)
    ap.add_argument("--flips", nargs="+", type=int)
    a = ap.parse_args()
    print("phi(a, .) bijective:", phi_bijective(), "; group order:", len(phi_group()))
    if a.bwh:
        report_bwh(*a.bwh)
    if a.rw:
        report_rw(*a.rw)
    if a.clumps:
        report_clumps(*a.clumps, hard_core=False)
    if a.rw_clumps:
        report_clumps(*a.rw_clumps, hard_core=True)
    if a.edges:
        report_edges(a.edges)
    if a.flips:
        print("n  f(n)  P(changing e_j changes the wedge on t < n + 2) for j = 0 .. 7, over 4000 random binary words")
        for n in tqdm(a.flips, desc="flips", file=sys.stderr):
            p = flip_profile(n, trials=4000)  # (2n + 2,)
            print(n, forgetting_depth(p), " ".join(f"{x:.3f}" for x in p[:8]), flush=True)


