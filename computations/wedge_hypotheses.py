# The C search


@dataclass(frozen=True, slots=True)
class CRuns:
    n: int
    hard_core: bool
    counts: np.ndarray  # (2, cap + 1) runs reaching each length, for c = 2, 3 (zero below n)
    dumped: list[tuple[int, int, int]]  # (c, prefix, reach) of every run with reach >= dump_from
    rw: np.ndarray  # (2, 3) RW witnesses for c = 2, 3 and r = 0, 1, 2 (zero without the guard)


def c_runs(n: int, hard_core: bool = False, cap: int | None = None, dump_from: int | None = None,
           threads: int = 2) -> CRuns:
    """`forced_runs` for c = 2 and 3 at once by `wedge_hypotheses.c` with OpenMP."""
    cap = 2 * n + 12 if cap is None else cap
    dump_from = cap + 1 if dump_from is None else dump_from
    split = min(n, 12)
    run = subprocess.run([str(_binary("wedge_hypotheses")), str(n), str(int(hard_core)), str(cap), str(dump_from),
                          str(split)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=True,
                         env={**os.environ, "OMP_NUM_THREADS": str(threads)})
    counts = np.zeros((2, cap + 1), dtype=np.int64)  # (2, cap + 1)
    rw = np.zeros((2, 3), dtype=np.int64)  # (2, 3)
    dumped = []
    for line in run.stdout.splitlines():
        tag, *f = line.split()
        x = [int(v) for v in f]
        if tag == "C":
            counts[x[0] - 2, x[1]] = x[2]
        elif tag == "S":
            dumped.append((x[0], x[1], x[2]))
        elif tag == "R":
            rw[x[0] - 2, x[1]] = x[2]
    return CRuns(n, hard_core, counts, dumped, rw)


# ---------------------------------------------------------------------------------------------------------------------
# Clumps, head depth, edges and flips


def survivors_at(n: int, c: int, hard_core: bool, runs: list[tuple[int, int]], L: int) -> set[tuple[int, ...]]:
    """The survivors of length L, from (prefix, reach) pairs that include every run reaching L."""
    return {forced_word(n, c, p, hard_core, L) for p, reach in runs if reach >= L}


def clumps(words: set[tuple[int, ...]], f: int) -> dict[tuple[int, ...], list[tuple[int, ...]]]:
    """The survivors grouped by their symbols from position f on."""
    out: dict[tuple[int, ...], list[tuple[int, ...]]] = {}
    for w in sorted(words):
        out.setdefault(w[f:], []).append(w)
    return out


def head_depth(words: set[tuple[int, ...]], word: tuple[int, ...], f_max: int) -> int:
    """The largest f <= f_max such that every binary head of length f followed by word[f:] is in the set."""
    f = 0
    while f < f_max and all(h + word[f + 1:] in words for h in itertools.product((1, 2), repeat=f + 1)):
        f += 1
    return f


def edge_census(n: int, c: int, hard_core: bool = False, progress: bool = False) -> dict[str, np.ndarray]:
    """Along every forced run for c: at each step k >= n the edge E_k of wedge values on e_k in {1, 2}, the edge E'_k of
    the values W_k[n - 1] (the second argument of the last phi) and the first argument a = W_{k-1}[n - 1]. Counts of
    (E_k index, E'_k index, a, survived) over all steps; E'_k = {1, 2} is index 2 of `EDGES`."""
    table = np.zeros((4, 4, 4, 2), dtype=np.int64)  # (E, E', a, survived)
    cone = Cone(n)
    bar = tqdm(total=1 << n, desc=f"edges n={n} c={c}", file=sys.stderr, disable=not progress, leave=False)

    def step() -> bool:
        k = len(cone.e)
        a = cone.W[k - 1][n - 1]
        vals, inner = set(), set()
        for s in (1, 2):
            cone.push(s)
            vals.add(cone.W[-1][n])
            inner.add(cone.W[-1][n - 1])
            cone.pop()
        s = cone.forced(c)
        ok = allowed(cone, s, hard_core)
        table[EDGES.index(frozenset(vals)), EDGES.index(frozenset(inner)), a, int(ok)] += 1
        if ok:
            cone.push(s)
        return ok

    def dfs(k: int) -> None:
        if k == n:
            depth = 0
            while depth < 3 * n and step():
                depth += 1
            for _ in range(depth):
                cone.pop()
            bar.update(1)
            return
        for s in (1, 2):
            cone.push(s)
            dfs(k + 1)
            cone.pop()

    dfs(0)
    bar.close()
    return {"table": table}


def flip_profile(n: int, trials: int = 2000, seed: int = 1) -> np.ndarray:
    """For each position j < 2n + 2, the fraction of random binary words of length 2n + 2 for which changing e_j
    (1 <-> 2) changes some wedge n e t, t < n + 2."""
    rng = np.random.default_rng(seed)
    L = 2 * n + 2
    e = rng.integers(1, 3, size=(trials, L), dtype=np.uint8)  # (trials, L)
    base = kit_wedge(n, e)  # (trials, n + 2)
    out = np.zeros(L)  # (L,)
    for j in range(L):
        f = e.copy()
        f[:, j] = 3 - f[:, j]
        out[j] = (kit_wedge(n, f) != base).any(axis=1).mean()
    return out


def forgetting_depth(profile: np.ndarray) -> int:
    """f(n): the least j at which changing e_j changes the wedge on the horizon for at least half of the words."""
    # profile: (2n + 2,) from `flip_profile`
    return int(np.argmax(profile >= 0.5))


