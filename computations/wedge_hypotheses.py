PHI: tuple[tuple[int, ...], ...] = ((0, 1, 3, 2), (3, 2, 1, 0), (3, 2, 0, 1), (3, 2, 1, 0))  # (4, 4): kit `phi`
PINV: tuple[tuple[int, ...], ...] = tuple(tuple(PHI[a].index(y) for y in range(4)) for a in range(4))  # (4, 4)
PHI_NP = np.array(PHI, dtype=np.uint8)  # (4, 4)
SQUARE = (0, 3, 1, 2)  # the cycle of the square that phi(a, .) preserves
EDGES = tuple(frozenset((SQUARE[i], SQUARE[(i + 1) % 4])) for i in range(4))  # the four edges


def phi(a: int, b: int) -> int:
    """The kit's `phi`."""
    return PHI[a][b]


def boundary(q: int) -> int:
    """The kit's `boundary`."""
    return 3 - q


def phi_bijective() -> bool:
    """phi(a, .) is a bijection of {0, 1, 2, 3} for every a."""
    return all(sorted(PHI[a]) == [0, 1, 2, 3] for a in range(4))


def phi_group() -> set[tuple[int, ...]]:
    """The group of permutations generated by phi(a, .), a = 0 .. 3, as tuples of images."""
    gens = [PHI[a] for a in range(4)]
    group = {(0, 1, 2, 3)}
    frontier = list(group)
    while frontier:
        g = frontier.pop()
        for h in gens:
            gh = tuple(h[g[x]] for x in range(4))
            if gh not in group:
                group.add(gh)
                frontier.append(gh)
    return group


# ---------------------------------------------------------------------------------------------------------------------
# The kit's definitions by rows (the independent check of `Cone`)


def kit_inverse(e: np.ndarray) -> np.ndarray:
    """inverse(t) for t < L of every word, by the kit's recursion one cone row at a time."""
    # e: (B, L) symbols
    B, L = e.shape
    rows = [(3 - e).astype(np.uint8)]  # row 0: (B, L)
    if L > 1:
        rows.append(PHI_NP[e[:, :-1], rows[0][:, 1:]])  # row 1: (B, L - 1)
    for t in range(2, L):
        rows.append(PHI_NP[rows[t - 2][:, 1:-1], rows[t - 1][:, 1:]])  # row t: (B, L - t)
    return np.stack([r[:, 0] for r in rows], axis=1)  # (B, L)


def kit_wedge(n: int, e: np.ndarray) -> np.ndarray:
    """wedge n e t for t < L - n of every word, by the kit's definition (n peels of the inverse)."""
    # e: (B, L)
    x = kit_inverse(e)  # (B, L)
    for _ in range(n):
        x = PHI_NP[x[:, :-1], x[:, 1:]]  # (B, len - 1)
    return x  # (B, L - n)


def dependence(t: int, L: int, trials: int = 200, seed: int = 0) -> set[int]:
    """The positions j < L at which changing e_j changes inverse(t), over random words of four symbols."""
    rng = np.random.default_rng(seed)
    e = rng.integers(0, 4, size=(trials, L), dtype=np.uint8)  # (trials, L)
    base = kit_inverse(e)[:, t]  # (trials,)
    out = set()
    for j in range(L):
        f = e.copy()
        f[:, j] = (f[:, j] + rng.integers(1, 4, size=trials, dtype=np.uint8)) % 4
        if (kit_inverse(f)[:, t] != base).any():
            out.add(j)
    return out


# ---------------------------------------------------------------------------------------------------------------------
# The incremental cone and the forced runs


class Cone:
    """The antidiagonals D_k[t] = cone(t, k - t) and the wedge diagonals W_k[m] = peel^m(inverse)(k - m), m <= n, of a
    growing word."""

    def __init__(self, n: int) -> None:
        self.n = n
        self.e: list[int] = []
        self.D: list[list[int]] = []  # D[k]: (k + 1,)
        self.W: list[list[int]] = []  # W[k]: (min(n, k) + 1,)

    def push(self, s: int) -> None:
        """Append e_k = s."""
        k = len(self.e)
        d = [3 - s]
        if k >= 1:
            d.append(PHI[self.e[k - 1]][d[0]])
            prev = self.D[k - 1]
            for t in range(2, k + 1):
                d.append(PHI[prev[t - 2]][d[t - 1]])
        w = [d[k]]
        for m in range(1, min(self.n, k) + 1):
            w.append(PHI[self.W[k - 1][m - 1]][w[m - 1]])
        self.e.append(s)
        self.D.append(d)
        self.W.append(w)

    def pop(self) -> None:
        self.e.pop()
        self.D.pop()
        self.W.pop()

    def wedge(self) -> int:
        """wedge n e (k - n) for the last k (needs k >= n)."""
        return self.W[-1][self.n]

    def forced(self, c: int) -> int:
        """The one symbol (0 .. 3) e_k that gives wedge n e (k - n) = c, by the backward pass (needs k >= n >= 1)."""
        n, k = self.n, len(self.e)
        Q, P = self.W[k - 1], self.D[k - 1]
        v = c
        for m in range(n, 0, -1):
            v = PINV[Q[m - 1]][v]
        d = v  # D_k[k]
        for t in range(k, 1, -1):
            d = PINV[P[t - 2]][d]
        return 3 - PINV[self.e[k - 1]][d]

    def edge(self) -> frozenset[int]:
        """The two wedge values at t = k - n for e_k = 1 and e_k = 2 (needs k >= n)."""
        out = set()
        for s in (1, 2):
            self.push(s)
            out.add(self.wedge())
            self.pop()
        return frozenset(out)


@dataclass(frozen=True, slots=True)
class Runs:
    n: int
    c: int
    hard_core: bool
    counts: np.ndarray  # (cap + 1,) number of free prefixes whose forced run reaches each length
    reach: np.ndarray  # (2^n,) the length each forced run reaches (prefix index: bit i is 1 when e_i = 2)


def allowed(cone: Cone, s: int, hard_core: bool) -> bool:
    """s is binary and, with the guard, does not put 1 after 1 at a position >= n."""
    if s not in (1, 2):
        return False
    return not (hard_core and s == 1 and len(cone.e) >= cone.n and cone.e[-1] == 1)


def forced_runs(n: int, c: int, hard_core: bool = False, cap: int | None = None, progress: bool = False) -> Runs:
    """Every free prefix of n binary symbols and its forced run for wedge value c, by depth-first search."""
    cap = 4 * n + 8 if cap is None else cap
    counts = np.zeros(cap + 1, dtype=np.int64)  # (cap + 1,)
    reach = np.zeros(1 << n, dtype=np.int64)  # (2^n,)
    cone = Cone(n)
    bar = tqdm(total=1 << n, desc=f"runs n={n} c={c}", file=sys.stderr, disable=not progress, leave=False)

    def run(prefix: int) -> None:
        k = n
        while k < cap:
            s = cone.forced(c)
            if not allowed(cone, s, hard_core):
                break
            cone.push(s)
            k += 1
        reach[prefix] = k
        counts[n:k + 1] += 1
        for _ in range(k - n):
            cone.pop()
        bar.update(1)

    def dfs(k: int, prefix: int) -> None:
        if k == n:
            run(prefix)
            return
        for s in (1, 2):
            cone.push(s)
            dfs(k + 1, prefix | ((s - 1) << k))
            cone.pop()

    dfs(0, 0)
    bar.close()
    return Runs(n, c, hard_core, counts, reach)


def forced_word(n: int, c: int, prefix: int, hard_core: bool = False, cap: int | None = None) -> tuple[int, ...]:
    """The free prefix (bit i is 1 when e_i = 2) followed by its forced run, as long as the run lasts (up to cap)."""
    cap = 4 * n + 8 if cap is None else cap
    cone = Cone(n)
    for i in range(n):
        cone.push(1 + ((prefix >> i) & 1))
    while len(cone.e) < cap:
        s = cone.forced(c)
        if not allowed(cone, s, hard_core):
            break
        cone.push(s)
    return tuple(cone.e)


def max_constant(n: int, c: int) -> int:
    """M(n, c): the largest k such that a binary word of length n + k has wedge n e t = c for t < k (kit
    `MaxHorizon`)."""
    return int(forced_runs(n, c).reach.max()) - n


def bwh_witnesses(n: int, c: int) -> list[tuple[int, ...]]:
    """Binary words of length 2n + 2 with wedge n e t = c for t < n + 2."""
    runs = forced_runs(n, c, cap=2 * n + 2)
    return [forced_word(n, c, int(p), cap=2 * n + 2) for p in np.flatnonzero(runs.reach >= 2 * n + 2)]


def rw_witnesses(n: int, r: int, c: int) -> list[tuple[int, ...]]:
    """The kit's `RWWitness n r c` prefixes: words of length 2n + r + 2."""
    L = 2 * n + r + 2
    runs = forced_runs(n, c, hard_core=True, cap=L)
    words = [forced_word(n, c, int(p), True, L) for p in np.flatnonzero(runs.reach >= L)]
    return [w for w in words if w[2 * n + r - 1] == 1 and w[2 * n + r] == 2]


