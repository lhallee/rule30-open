"""Forced runs of the kit's wedge hypotheses BWH and RW (kit main, `Rule30WedgeBridge`), and what kills their survivors.

Symbols are 0 .. 3, `phi` is the kit's table, `boundary q = 3 - q`. For a stream e the kit's cone is
cone(0, j) = boundary(e_j), cone(1, j) = phi(e_j, boundary(e_{j+1})), cone(t+2, j) = phi(cone(t, j+1), cone(t+1, j+1)),
inverse(t) = cone(t, 0), peel x t = phi(x_t, x_{t+1}) and wedge n e = peel^n(inverse e). A binary symbol is 1 or 2.

- BWH(n, c): no binary word of length 2n + 2 has wedge n e t = c for t < n + 2 (kit: for n >= 7, c in {2, 3}).
- RW(n, r, c): no binary word of length 2n + r + 2 with no 1 after a 1 at positions i >= n, wedge c for t < n + r + 2,
  and e_{2n+r-1} = 1, e_{2n+r} = 2 (kit `RWWitness`); `SmallRW` is RW for 1 <= n < 7, r <= 2, c in {2, 3}.

phi(a, .) is a bijection for every a (`phi_bijective`). The cone and the wedge are built antidiagonal by antidiagonal
(`Cone`): adding e_k fills D_k[t] = cone(t, k - t) and W_k[m] = peel^m(inverse)(k - m), so wedge n e (k - n) = W_k[n],
and each new entry is phi(old entry, newer entry), a bijection of e_k. So given e_0 .. e_{k-1} exactly one of the four
symbols gives wedge c at t = k - n, and a backward pass (`Cone.forced`) finds it. Past the first n free symbols every
binary prefix has at most one binary child that keeps the wedge equal to c: BWH(n, c) and RW(n, ., c) are statements
about the 2^n forced runs, one from each free prefix (`forced_runs`; `wedge_hypotheses.c` for large n).

The three permutations phi(0, .) = (2 3), phi(1, .) = phi(3, .) = (0 3)(1 2) and phi(2, .) = (0 3 1 2) generate the
dihedral group of order 8 of the square 0 - 3 - 1 - 2 (`phi_group`), and {1, 2} is an edge of it. So the values the
wedge takes on the two binary choices of e_k form an edge of the square (`edge_images`): a run survives a step for c
exactly when c lies on that edge, and each value lies on two of the four edges.

The kit's cone depends on few symbols: inverse(t) depends on e_j only for floor(t/2) <= j <= t (`dependence`), so
wedge n e t never depends on e_j for j < floor(t/2). A clump is a set of survivors at one length that differ only in
their first f symbols; `head_depth` is the largest f for which every one of the 2^f heads with a survivor's tail survives.
The forgetting depth f(n) (`forgetting_depth`) is the least j at which changing e_j changes some wedge n e t, t < n + 2,
for at least half of the binary words of length 2n + 2 (sampled, `flip_profile`).

    python -m computations.wedge_hypotheses --bwh 7 26          # BWH survivors, M(n), witnesses: about 30 s
    python -m computations.wedge_hypotheses --bwh 27 31         # the same for n = 27 to 31: about 19 min
    python -m computations.wedge_hypotheses --rw 1 26           # RW survivors and witnesses: about 45 s
    python -m computations.wedge_hypotheses --clumps 8 24 --rw-clumps 10 24   # head depths: about 30 s
    python -m computations.wedge_hypotheses --edges 14          # edge statistics of deaths: a few seconds
    python -m computations.wedge_hypotheses --flips 8 12 16 20 24 28 32   # forgetting depth f(n): about 20 s

The C searches use two OpenMP threads.
"""

