"""The block algebra of an elementary rule: its k-block binary operation, the group of its translations, its monoid.

Group the cells of a row into blocks of k. One step of an elementary rule sends the 2k cells of two adjacent blocks
a (left) and b (right) to the k cells one place to the right of a's first cell:

    (a * b)_m = f(w_m, w_{m+1}, w_{m+2}),  w = a followed by b,  m = 0, ..., k - 1,

so the staggered automaton is the binary operation `*` on {0, 1}^k, the form in which Moore's algebraic prediction
theorems are stated. A block is an integer, bit m the cell at offset m. `right_translations` are the maps
a -> a * b (one per b), `left_translations` the maps b -> a * b (one per a). The multiplication monoid is the
transformation monoid the two families generate; its group of units and the groups at its idempotents decide whether
it is solvable in the sense of Krohn-Rhodes theory (every subgroup solvable).

    python -m computations.block_algebra   # the table of the entry for Rules 30, 45, 90, 110 and 150 (about 75 s)
"""

from __future__ import annotations

import argparse
import math
import sys
from collections.abc import Iterable

import numpy as np
from tqdm.auto import tqdm

Perm = tuple[int, ...]


def block_table(rule: int, k: int) -> np.ndarray:
    """The table of `*` for the elementary rule `rule` on k-blocks: entry [a, b] is a * b."""
    n = 1 << k
    table = np.zeros((n, n), dtype=np.int64)  # (2^k, 2^k)
    for a in range(n):
        for b in range(n):
            w = a | (b << k)
            out = 0
            for m in range(k):
                left, center, right = (w >> m) & 1, (w >> (m + 1)) & 1, (w >> (m + 2)) & 1
                out |= ((rule >> (4 * left + 2 * center + right)) & 1) << m
            table[a, b] = out
    return table  # (2^k, 2^k)


def right_translations(table: np.ndarray) -> list[Perm]:
    """The distinct maps a -> a * b, one for each right argument b."""
    # table: (2^k, 2^k)
    return sorted(set(tuple(int(v) for v in table[:, b]) for b in range(table.shape[1])))


def left_translations(table: np.ndarray) -> list[Perm]:
    """The distinct maps b -> a * b, one for each left argument a."""
    # table: (2^k, 2^k)
    return sorted(set(tuple(int(v) for v in table[a, :]) for a in range(table.shape[0])))


def compose(s: Perm, t: Perm) -> Perm:
    """The map x -> s(t(x))."""
    return tuple(s[x] for x in t)


def inverse(p: Perm) -> Perm:
    """The inverse of a permutation."""
    out = [0] * len(p)
    for x, y in enumerate(p):
        out[y] = x
    return tuple(out)


def group_order(gens: list[Perm]) -> int:
    """The order of the permutation group `gens` generate, by the Schreier-Sims algorithm with base 0, 1, ..., n-1:
    the product of the orbit lengths of j under the pointwise stabilizer of 0, ..., j-1."""
    n = len(gens[0])
    ident: Perm = tuple(range(n))
    strong: list[Perm] = [g for g in gens if g != ident]

    def fixes(g: Perm, j: int) -> bool:
        return all(g[i] == i for i in range(j))

    def transversal(j: int) -> dict[int, Perm]:
        level = [g for g in strong if fixes(g, j)]
        reps = {j: ident}
        queue = [j]
        while queue:
            x = queue.pop()
            for g in level:
                y = g[x]
                if y not in reps:
                    reps[y] = compose(g, reps[x])
                    queue.append(y)
        return reps

    def sift(g: Perm, reps: list[dict[int, Perm]], start: int) -> Perm:
        for j in range(start, n):
            if g[j] not in reps[j]:
                return g
            g = compose(inverse(reps[j][g[j]]), g)
        return g

    changed = True
    while changed:
        changed = False
        reps = [transversal(j) for j in range(n)]
        for j in range(n):
            level = [g for g in strong if fixes(g, j)]
            for x, u in reps[j].items():
                for g in level:
                    schreier = compose(inverse(reps[j][g[x]]), compose(g, u))
                    residue = sift(schreier, reps, j + 1)
                    if residue != ident:
                        strong.append(residue)
                        changed = True
                        break
                if changed:
                    break
            if changed:
                break
    order = 1
    for r in reps:
        order *= len(r)
    return order


def closure(gens: Iterable[Perm], progress: bool = False) -> set[Perm]:
    """The transformation monoid generated by `gens` (with the identity), by breadth-first search."""
    gens = list(gens)
    ident: Perm = tuple(range(len(gens[0])))
    seen = {ident}
    frontier = [ident]
    bar = tqdm(desc="monoid", file=sys.stderr, disable=not progress)
    while frontier:
        nxt = []
        for s in frontier:
            for g in gens:
                t = compose(g, s)
                if t not in seen:
                    seen.add(t)
                    nxt.append(t)
        bar.update(len(nxt))
        frontier = nxt
    bar.close()
    return seen


def is_solvable(group: set[Perm]) -> bool:
    """Whether a finite permutation group, given by all its elements, is solvable (its derived series reaches 1)."""
    current = group
    while len(current) > 1:
        commutators = {compose(compose(inverse(x), inverse(y)), compose(x, y)) for x in current for y in current}
        derived = closure(commutators)
        if len(derived) == len(current):
            return False
        current = derived
    return True


def idempotent_groups(monoid: set[Perm]) -> dict[frozenset[int], set[Perm]]:
    """For each image X of a non-identity idempotent of the monoid, the group of permutations of X induced by the
    elements that map X onto X. It is isomorphic to the maximal subgroup at every idempotent with image X."""
    images = {frozenset(s) for s in monoid if len(set(s)) < len(s) and all(s[x] == x for x in set(s))}
    out: dict[frozenset[int], set[Perm]] = {}
    for image in images:
        points = sorted(image)
        index = {x: i for i, x in enumerate(points)}
        perms = set()
        for s in monoid:
            if all(s[x] in image for x in points) and len({s[x] for x in points}) == len(points):
                perms.add(tuple(index[s[x]] for x in points))
        out[image] = perms
    return out


def large_rank_groups(monoid: set[Perm], min_rank: int) -> dict[frozenset[int], set[Perm]]:
    """`idempotent_groups` restricted to images of at least `min_rank` points. An element that maps an image X onto
    itself has rank at least |X|, so only the elements of rank at least `min_rank` are scanned."""
    big = [s for s in monoid if min_rank <= len(set(s)) < len(s)]
    images = {frozenset(s) for s in big if all(s[x] == x for x in set(s))}
    out: dict[frozenset[int], set[Perm]] = {}
    for image in images:
        points = sorted(image)
        index = {x: i for i, x in enumerate(points)}
        out[image] = {tuple(index[s[x]] for x in points) for s in big
                      if {s[x] for x in points} == image}
    return out


def period(s: Perm) -> int:
    """The period of the cyclic semigroup s, s^2, ...: the least common multiple of the cycle lengths of s. A finite
    monoid has an element of period divisible by a prime p exactly when one of its subgroups has order divisible by p,
    so when every subgroup is solvable, C_p divides the monoid exactly when some element has period divisible by p."""
    n = len(s)
    visited = [False] * n  # (n,)
    out = 1
    for x in range(n):
        y = x
        for _ in range(n):  # after n steps every point is on a cycle
            y = s[y]
        if visited[y]:
            continue
        length, z = 0, y
        while True:
            visited[z] = True
            z = s[z]
            length += 1
            if z == y:
                break
        out = out * length // math.gcd(out, length)
    return out


def element_periods(monoid: Iterable[Perm]) -> set[int]:
    """The set of periods of the elements of a transformation monoid."""
    return {period(s) for s in monoid}


def max_nonunit_rank(table: np.ndarray) -> int:
    """The largest image size of a left translation b -> a * b that is not a bijection."""
    # table: (2^k, 2^k)
    ranks = [len(set(p)) for p in left_translations(table)]
    return max((r for r in ranks if r < table.shape[0]), default=0)


def phi_state(s: int, k: int) -> Perm:
    """The state PhiS s x = x xor (2x or 4x or s) of the kit's automaton group 2369, modulo 2^k, written on blocks:
    bit e of the integer is cell k - 1 - e of the block."""
    def rev(x: int) -> int:
        return int(format(x, f"0{k}b")[::-1], 2)

    mask = (1 << k) - 1
    return tuple(rev((y ^ ((2 * y) | (4 * y) | s)) & mask) for y in (rev(a) for a in range(1 << k)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kmax", type=int, default=6, help="largest block size for the group orders")
    parser.add_argument("--monoid-kmax", type=int, default=3, help="largest block size for the full monoid")
    parser.add_argument("--large-k", type=int, default=5, help="largest block size for Rule 110's groups of rank >= 5")
    parser.add_argument("--period-kmax", type=int, default=5, help="largest block size for the periods of Rules 90, 150")
    parser.add_argument("--rule30-period-k", type=int, default=4, help="block size for the periods of Rule 30's monoid")
    args = parser.parse_args()
    for rule in (30, 45, 90, 150, 110):
        for k in range(2, args.kmax + 1):
            table = block_table(rule, k)  # (2^k, 2^k)
            units = [p for p in right_translations(table) if len(set(p)) == len(p)]
            order = group_order(units) if units else 1
            print(f"rule {rule} k {k}: right translations {len(right_translations(table))}, bijective {len(units)}, "
                  f"group order 2^{order.bit_length() - 1 if order & (order - 1) == 0 else order}, "
                  f"largest non-bijective left translation rank {max_nonunit_rank(table)}")
        for k in range(2, args.monoid_kmax + 1):
            table = block_table(rule, k)  # (2^k, 2^k)
            monoid = closure(right_translations(table) + left_translations(table), progress=True)
            groups = idempotent_groups(monoid)
            orders = sorted({(len(x), len(g)) for x, g in groups.items()})
            print(f"rule {rule} k {k}: monoid {len(monoid)}, (rank, group order) at idempotents {orders}, "
                  f"all solvable {all(is_solvable(g) for g in groups.values())}, "
                  f"units {sum(1 for s in monoid if len(set(s)) == len(s))}, periods {sorted(element_periods(monoid))}")
    for k in range(4, args.large_k + 1):
        table = block_table(110, k)  # (2^k, 2^k)
        monoid = closure(right_translations(table) + left_translations(table), progress=True)
        groups = large_rank_groups(monoid, 5)
        print(f"rule 110 k {k}: monoid {len(monoid)}, groups at idempotents of rank >= 5: "
              f"{sorted({(len(x), len(g)) for x, g in groups.items()})}, periods {sorted(element_periods(monoid))}")
    for rule in (90, 150):
        for k in range(4, args.period_kmax + 1):
            table = block_table(rule, k)  # (2^k, 2^k)
            monoid = closure(right_translations(table) + left_translations(table), progress=True)
            print(f"rule {rule} k {k}: monoid {len(monoid)}, periods {sorted(element_periods(monoid))}")
    if args.rule30_period_k >= 4:
        table = block_table(30, args.rule30_period_k)  # (2^k, 2^k)
        monoid = closure(right_translations(table) + left_translations(table), progress=True)
        print(f"rule 30 k {args.rule30_period_k}: monoid {len(monoid)}, periods {sorted(element_periods(monoid))}")


if __name__ == "__main__":
    main()
